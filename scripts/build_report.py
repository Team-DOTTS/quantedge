# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------
def _minus(s: str) -> str:
    return s.replace("-", "\\textminus{}", 1) if s.startswith("-") else s


def p(x, d=1) -> str:
    return _minus(f"{x * 100:.{d}f}\\%")


def usd(x) -> str:
    return ("\\textminus{}" if x < 0 else "") + f"\\${abs(x):,.0f}"


def usdm(x) -> str:
    return f"\\${x / 1e6:.2f}m"


def f2(x) -> str:
    return _minus(f"{x:.2f}")


class Macros:
    def __init__(self):
        self.lines = ["% Generated by scripts/build_report.py. Do not edit by hand."]

    def __setitem__(self, name: str, value: str):
        assert name.isalpha(), name
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path: Path):
        path.write_text("\n".join(self.lines) + "\n")


def tex_table(df: pd.DataFrame, path: Path, align: str | None = None, bold_first: bool = False):
    """Minimal booktabs tabular (cells must already be LaTeX-safe strings)."""
    cols = list(df.columns)
    align = align or "l" + "r" * len(cols)
    rows = [f"\\begin{{tabular}}{{{align}}}", "\\toprule",
            " & ".join([df.index.name or ""] + cols) + " \\\\", "\\midrule"]
    for i, (idx, r) in enumerate(df.iterrows()):
        cells = [str(idx)] + [str(v) for v in r.values]
        if bold_first and i == 0:
            cells = [f"\\textbf{{{c}}}" for c in cells]
        rows.append(" & ".join(cells) + " \\\\")
    rows += ["\\bottomrule", "\\end{tabular}"]
    path.write_text("\n".join(rows) + "\n")


def esc(s: str) -> str:
    return s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("√", "$\\sqrt{}$")


